export function getUniversitiesByCountry(countryCode: string): GlobalUniversity[] {
  return globalUniversities.filter((u) => u.country === countryCode);
}

export function getUniversityByKey(key: string): GlobalUniversity | undefined {
  return globalUniversities.find((u) => u.key === key);
}

const keys = globalUniversities.map((u) => u.key);
const duplicates = keys.filter((k, i) => keys.indexOf(k) !== i);
if (duplicates.length > 0) {
  throw new Error(`Duplicate university keys: ${duplicates.join(', ')}`);
}